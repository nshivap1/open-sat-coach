type T = [string, string, string]; // [suffix, name, definition]
function types(skillId: string, list: T[]): QuestionType[] {
  return list.map(([suffix, name, definition]) => ({ id: `${skillId}.${suffix}`, skillId, name, definition }));
}

function skill(
  id: string, domainId: string, officialName: string, studentName: string, tests: string,
  cues: string[], commonMistakes: string[], strategies: string[], prerequisites: string[], typeList: T[],
): Skill {
  return { id, domainId, officialName, studentName, tests, cues, commonMistakes, strategies, prerequisites, types: types(id, typeList) };
}

