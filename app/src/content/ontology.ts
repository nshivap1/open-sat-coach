export const SKILL_BY_ID: Record<string, Skill> = Object.fromEntries(SKILLS.map((s) => [s.id, s]));
export const DOMAIN_BY_ID: Record<string, Domain> = Object.fromEntries(DOMAINS.map((d) => [d.id, d]));
export function skillsInDomain(domainId: string): Skill[] {
  return SKILLS.filter((s) => s.domainId === domainId);
}
export function typeById(typeId: string): QuestionType | undefined {
  for (const s of SKILLS) for (const t of s.types) if (t.id === typeId) return t;
  return undefined;
}
